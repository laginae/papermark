let language = 'en';
function t(key, values = {}) {
  const pair = messages[key];
  if (!pair) throw new Error(`Unknown translation key: ${key}`);
  return pair[language === 'zh-CN' ? 1 : 0].replace(/\{(\w+)\}/g, (match, name) => String(values[name] ?? match));
}
function setLanguage(value) { language = value === 'zh-CN' ? 'zh-CN' : 'en'; return language; }
function getLanguage() { return language; }
function uiError(key, values = {}) {
  const error = new Error(t(key, values)); error.i18nKey = key; error.i18nValues = values; return error;
}
function restoreLanguage(storage) {
  try { return setLanguage(storage?.getItem('papermark.language')); } catch { return setLanguage('en'); }
}
function saveLanguage(value, storage) {
  setLanguage(value); try { storage?.setItem('papermark.language', language); } catch {}
}
function translateDom(root) {
  root.documentElement.lang = language; root.title = t('app.title');
  for (const element of root.querySelectorAll('[data-i18n]')) element.textContent = t(element.dataset.i18n);
  for (const attribute of ['aria-label', 'title', 'content']) {
    for (const element of root.querySelectorAll(`[data-i18n-${attribute}]`)) element.setAttribute(attribute, t(element.getAttribute(`data-i18n-${attribute}`)));
  }
  root.body.dataset.dropLabel = t('drop.release');
}
